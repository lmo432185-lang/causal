def wrap(p,width=68):
 # CJK approximate full-width; ASCII half-width
 lines=[];line='';w=0
 for ch in p:
  cw=1 if ord(ch)>255 else .55
  if w+cw>width:lines.append(line);line='';w=0
  line+=ch;w+=cw
 if line:lines.append(line)
 return '\n'.join(lines)
